import sharp from "sharp";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
const branding = JSON.parse(
  await readFile(new URL("src/lib/pwa-branding.json", root), "utf8"),
);
const source = await readFile(new URL("public" + branding.artwork, root));
const layout = { regular: 0.84, maskable: 0.72 };
const revision = createHash("sha256")
  .update(source)
  .update(
    JSON.stringify({ background: branding.background, layout, opaque: true }),
  )
  .digest("hex")
  .slice(0, 12);
const logo = await sharp(source, { density: 144 }).trim().png().toBuffer();
const dir = new URL("public/icons/", root);
await mkdir(dir, { recursive: true });
async function render(size, maskable = false) {
  const extent = Math.round(
    size * (maskable ? layout.maskable : layout.regular),
  );
  const foreground = await sharp(logo)
    .resize(extent, extent, { fit: "inside" })
    .png()
    .toBuffer();
  return sharp({
    create: {
      width: size,
      height: size,
      channels: 3,
      background: branding.background,
    },
  })
    .composite([{ input: foreground, gravity: "centre" }])
    .removeAlpha()
    .png()
    .toBuffer();
}
const urls = {};
for (const size of [180, 192, 512, 1024])
  for (const maskable of size === 512 ? [false, true] : [false]) {
    const bytes = await render(size, maskable),
      base = `app-${size}${maskable ? "-maskable" : ""}`,
      file = `${base}-${revision}.png`;
    await writeFile(new URL(file, dir), bytes);
    // Old installed manifests/loading bundles can still request these compatibility URLs.
    await writeFile(new URL(base + ".png", dir), bytes);
    urls[maskable ? "maskable" : size === 180 ? "apple" : "icon" + size] =
      "/icons/" + file;
  }
const sizes = [32, 48, 64, 256],
  pngs = await Promise.all(
    sizes.map(async (size) =>
      sharp(await render(size))
        .ensureAlpha()
        .png()
        .toBuffer(),
    ),
  ),
  header = Buffer.alloc(6),
  entries = Buffer.alloc(16 * sizes.length);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = 6 + entries.length;
for (let i = 0; i < sizes.length; i++) {
  const start = i * 16;
  entries[start] = sizes[i] === 256 ? 0 : sizes[i];
  entries[start + 1] = entries[start];
  entries.writeUInt16LE(1, start + 4);
  entries.writeUInt16LE(32, start + 6);
  entries.writeUInt32LE(pngs[i].length, start + 8);
  entries.writeUInt32LE(offset, start + 12);
  offset += pngs[i].length;
}
const ico = Buffer.concat([header, entries, ...pngs]),
  favicon = `favicon-${revision}.ico`;
await writeFile(new URL(favicon, dir), ico);
await writeFile(new URL("public/favicon.ico", root), ico);
urls.favicon = "/icons/" + favicon;
await writeFile(
  new URL("src/lib/pwa-icons.ts", root),
  "// Generated by scripts/generate-icons.mjs from the shared splash artwork.\nexport const pwaIcons = " +
    JSON.stringify(urls, null, 2) +
    " as const;\n",
);
const manifestPath = new URL("public/manifest.json", root),
  manifest = JSON.parse(await readFile(manifestPath, "utf8"));
manifest.icons = [
  { src: urls.icon192, type: "image/png", sizes: "192x192", purpose: "any" },
  { src: urls.icon512, type: "image/png", sizes: "512x512", purpose: "any" },
  {
    src: urls.maskable,
    type: "image/png",
    sizes: "512x512",
    purpose: "maskable",
  },
];
manifest.background_color = branding.background;
manifest.theme_color = branding.background;
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
console.log(
  `Generated matching launcher, maskable, Apple and browser icons (${revision}).`,
);
