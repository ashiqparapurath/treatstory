import sharp from "sharp";
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir, readdir, unlink } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const branding = JSON.parse(
  await readFile(new URL("src/lib/pwa-branding.json", root), "utf8"),
);
const artwork = await readFile(new URL("public" + branding.artwork, root));
// Device CSS pixels stay portrait-oriented in Apple's startup-image media queries.
const devices = [
  [320, 568, 2],
  [375, 667, 2],
  [414, 736, 3],
  [375, 812, 3],
  [414, 896, 2],
  [414, 896, 3],
  [360, 780, 3],
  [390, 844, 3],
  [428, 926, 3],
  [393, 852, 3],
  [430, 932, 3],
  [402, 874, 3],
  [440, 956, 3],
  [420, 912, 3],
  [768, 1024, 2],
  [820, 1180, 2],
  [834, 1194, 2],
  [1024, 1366, 2],
  [834, 1210, 2],
  [1032, 1376, 2],
  [744, 1133, 2],
];
const dir = new URL("public/splash/startup/", root);
await mkdir(dir, { recursive: true });
const images = [],
  keep = new Set();
for (const [cssWidth, cssHeight, dpr] of devices)
  for (const orientation of ["portrait", "landscape"]) {
    const width = (orientation === "portrait" ? cssWidth : cssHeight) * dpr,
      height = (orientation === "portrait" ? cssHeight : cssWidth) * dpr;
    const hash = createHash("sha256")
      .update(artwork)
      .update(
        JSON.stringify({ background: branding.background, width, height }),
      )
      .digest("hex")
      .slice(0, 12);
    const name = `launch-${width}x${height}-${hash}.png`;
    keep.add(name);
    const logo = await sharp(artwork, { density: 144 })
      .resize({
        width: Math.min(width, 640 * dpr),
        height: Math.floor(height * 0.8),
        fit: "inside",
      })
      .png()
      .toBuffer();
    await sharp({
      create: { width, height, channels: 3, background: branding.background },
    })
      .composite([{ input: logo, gravity: "centre" }])
      .png({ palette: true, colours: 256, compressionLevel: 9 })
      .toFile(new URL(name, dir).pathname);
    images.push({
      url: "/splash/startup/" + name,
      media: `(device-width: ${cssWidth}px) and (device-height: ${cssHeight}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: ${orientation})`,
      width,
      height,
    });
  }
for (const file of await readdir(dir))
  if (/^launch-\d+x\d+-[a-f0-9]{12}\.png$/.test(file) && !keep.has(file))
    await unlink(new URL(file, dir));
await writeFile(
  new URL("src/lib/pwa-startup-images.ts", root),
  "// Generated by scripts/generate-pwa-splash.mjs. Do not edit.\nexport const pwaStartupImages = " +
    JSON.stringify(images, null, 2) +
    " as const;\n",
);
const manifestPath = new URL("public/manifest.json", root),
  manifest = JSON.parse(await readFile(manifestPath, "utf8"));
manifest.background_color = branding.background;
manifest.theme_color = branding.background;
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
console.log(
  `Generated ${images.length} startup images on ${branding.background}.`,
);
