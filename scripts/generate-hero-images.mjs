// Build responsive, centre-cropped copies from the lossless source; never modify it.
import sharp from "sharp";
import { mkdir, writeFile, readdir, unlink } from "node:fs/promises";
import { createHash } from "node:crypto";
const directory = new URL("../public/img/hero/", import.meta.url),
  source = new URL("../public/img/landing-hero.png", import.meta.url);
await mkdir(directory, { recursive: true });
for (const name of await readdir(directory))
  if (/^home-(mobile|tablet|desktop)-\d+-[a-f0-9]{12}\.(avif|webp)$/.test(name))
    await unlink(new URL(name, directory));
const specs = {
  mobile: { ratio: 1.3, widths: [480, 768, 1200] },
  tablet: { ratio: 1.18, widths: [480, 768, 1110] },
  desktop: { ratio: 1.4, widths: [480, 768, 1317] },
};
const manifest = {};
for (const [name, { ratio, widths }] of Object.entries(specs)) {
  manifest[name] = {};
  for (const format of ["avif", "webp"]) {
    const files = [];
    for (const width of widths) {
      let pipeline = sharp(source.pathname).resize({
        width,
        height: Math.round(width / ratio),
        fit: "cover",
        position: "centre",
        withoutEnlargement: true,
      });
      pipeline =
        format === "avif"
          ? pipeline.avif({ quality: 65, effort: 5 })
          : pipeline.webp({ quality: 80, effort: 5 });
      const bytes = await pipeline.toBuffer(),
        hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12),
        file = `home-${name}-${width}-${hash}.${format}`;
      await writeFile(new URL(file, directory), bytes);
      files.push({ src: "/img/hero/" + file, width, bytes: bytes.length });
    }
    manifest[name][format] = files;
  }
}
await writeFile(
  new URL("../src/lib/hero-images.ts", import.meta.url),
  "// Generated by scripts/generate-hero-images.mjs. Content hashes prevent stale image versions.\nexport const heroImages = " +
    JSON.stringify(manifest, null, 2) +
    " as const;\n",
);
console.log("Generated 18 responsive AVIF/WebP assets from the original PNG.");
